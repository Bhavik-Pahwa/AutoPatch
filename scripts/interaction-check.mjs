import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
const browser=await chromium.launch()
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'})
try{
 await page.goto('http://localhost:5173/healing')
 await page.getByRole('heading',{name:'Self-Healing Engine.'}).waitFor()
 await page.keyboard.press('Control+k')
 await page.getByRole('textbox',{name:'Command search'}).fill('Invoice')
 await page.getByRole('button',{name:/Invoice Download Automation/}).click()
 await page.getByRole('heading',{name:'Invoice Download Automation.'}).waitFor()
 await page.getByRole('button',{name:'Expand graph',exact:true}).click()
 const dialog=page.getByRole('dialog')
 await dialog.getByRole('heading',{name:'Workflow canvas'}).waitFor()
 await dialog.locator('.react-flow__node').nth(2).focus()
 await page.keyboard.press('Enter')
 await dialog.getByText("page.getByRole('table', { name: 'Invoices' })",{exact:true}).waitFor()
 await page.keyboard.press('Escape')
 await page.goto('http://localhost:5173/healing?scenario=relocated')
 await page.getByRole('heading',{name:'Self-Healing Engine.'}).waitFor()
 await page.getByLabel('Playback speed').selectOption('2')
 await page.getByRole('button',{name:'Play simulation',exact:true}).click()
 await page.getByRole('link',{name:'Inspect full repair evidence'}).waitFor({timeout:20000})
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('autopatch-demo-v1')).state.workflows[0].version),'v1.4')
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:'Expand graph',exact:true}).click()
 await page.getByRole('dialog').getByRole('heading',{name:'Recovery lifecycle'}).waitFor()
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 await page.keyboard.press('Escape')
 console.log('PASS: keyboard command search, keyboard graph selection, full-screen mobile graph, 2× automatic playback, element-relocation repair.')
}finally{await browser.close()}
